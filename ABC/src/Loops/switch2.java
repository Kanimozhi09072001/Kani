package Loops;

public class switch2 {

	public static void main(String[] args) {
		String veggies = "carrot";
		switch(veggies) {
		case "corn":
			System.out.println("corn");
			break;
		case "potato":
			System.out.println("potato");
			break;
		case "radish":
			System.out.println("radish");
			break;
		default:
			System.out.println("no match");
			break;
			
		}

	}

}
