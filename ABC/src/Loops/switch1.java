package Loops;

public class switch1 {

	public static void main(String[] args) {
		int age = 3;
		switch(age) {
		case 1:
			System.out.println("new born");
			break;
		case 2:
			System.out.println("infant");
			break;
		case 3:
			System.out.println("toddler");
			break;
		default:
			System.out.println("no match");
			break;
			
		}

	}

}
