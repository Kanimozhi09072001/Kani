package Loops;

public class switch3 {

	public static void main(String[] args) {
		char letter = 'a';
		switch(letter) {
		case 'c':
			System.out.println("corn");
			break;
		case 'b':
			System.out.println("potato");
			break;
		case 'a':
			System.out.println("radish");
			break;
		default:
			System.out.println("no match");
			break;
			
		}

	}

}
